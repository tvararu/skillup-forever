"""Write Data/PatternSources.lua from Crafter's Journal's per-profession recipe tables.

Usage: python3 tools/gen_pattern_sources.py <CraftersJournal checkout>

Keeps what SkillUp's own data lacks about where a recipe is learnt: its Merchant's Favor
price and the reputation that asks, a pattern's reputation, its specialisation, whether
the profession teaches it outright, whether Forever teaches it at all, the pattern's vendor
price, the learn skill, and whether its product binds on pickup.
"""

import re
import sys
from pathlib import Path

PROFESSIONS = (
    "Alchemy",
    "Blacksmithing",
    "Cooking",
    "Enchanting",
    "Engineering",
    "FirstAid",
    "Leatherworking",
    "Tailoring",
)

RECIPE = re.compile(r"^\s*\[(\d+)\] = \{ name = (\"(?:[^\"\\]|\\.)*\"), (.*) \},\s*$")
NUMBER = {key: re.compile(rf"\b{key} = (\d+)") for key in ("favor", "favorRep", "train", "scrollPrice")}
FLAG = {key: re.compile(rf"\b{key} = true") for key in ("basic", "gone", "bop", "trainer")}
TEXT = {key: re.compile(rf"\b{key} = (\"[A-Za-z]+\")") for key in ("spec", "faction")}
REP = re.compile(r"\brep = \{ (\d+), (\d+) \}")
ORDER = (
    "train",
    "favor",
    "favorRep",
    "rep",
    "spec",
    "faction",
    "scrollPrice",
    "basic",
    "trainer",
    "gone",
    "bop",
)


def parse(text: str) -> dict[int, dict[str, str]]:
    """Each recipe's fields, as Lua source, keyed by spell ID."""
    recipes: dict[int, dict[str, str]] = {}
    for line in text.splitlines():
        match = RECIPE.match(line)
        if not match:
            continue
        spell, rest = int(match.group(1)), match.group(3)
        # Reagents and outputs follow; only the fields before them describe the source.
        head = rest.split(" r = {", 1)[0]
        fields: dict[str, str] = {}
        for key, pattern in NUMBER.items():
            found = pattern.search(head)
            if found:
                fields[key] = found.group(1)
        for key, pattern in FLAG.items():
            if pattern.search(rest):
                fields[key] = "true"
        for key, pattern in TEXT.items():
            found = pattern.search(head)
            if found:
                fields[key] = found.group(1)
        found = REP.search(head)
        if found:
            fields["rep"] = "{ " + found.group(1) + ", " + found.group(2) + " }"
        recipes[spell] = fields
    return recipes


def render(recipes: dict[int, dict[str, str]]) -> str:
    lines = [
        "-- luacheck: ignore",
        "-- stylua: ignore",
        "-- Generated by tools/gen_pattern_sources.py from Crafter's Journal's recipe tables; do not edit.",
        "---@type string, SkillUpNamespace",
        "local _, ns = ...",
        "",
        "-- [spellID] = { train, favor, favorRep, rep = { factionID, standing }, spec, faction, scrollPrice,",
        "-- basic, trainer, gone, bop }",
        "ns.PatternSources = {",
    ]
    for spell in sorted(recipes):
        fields = recipes[spell]
        parts = [f"{key} = {fields[key]}" for key in ORDER if key in fields]
        lines.append(f"\t[{spell}] = {{ {', '.join(parts)} }},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    data = Path(sys.argv[1]) / "Data"
    recipes: dict[int, dict[str, str]] = {}
    for profession in PROFESSIONS:
        recipes.update(parse((data / f"{profession}.lua").read_text(encoding="utf-8")))
    out = Path(__file__).resolve().parent.parent / "Data" / "PatternSources.lua"
    out.write_text(render(recipes), encoding="utf-8")
    print(f"{out.name}: {len(recipes)} recipes")


if __name__ == "__main__":
    main()
